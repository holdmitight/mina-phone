export function ja(text: string): string {
  if (Object.prototype.hasOwnProperty.call(labels, text)) return labels[text];
  return text
    .replace(/^已输入(\d+)位密码$/, "$1桁入力済み")
    .replace(/^(\d+) 张照片$/, "$1枚の写真")
    .replace(/^(\d+) 个项目$/, "$1項目")
    .replace(/^(\d+) 条消息$/, "$1件のメッセージ")
    .replace(/^(\d+) 次赞$/, "いいね！$1件")
    .replace(/^搜索(.+)$/, (_, value: string) => `${ja(value)}を検索`);
}
